"""Generate src/os9names.h (OS-9 service request names) from NitrOS-9 defs/os9.d.
usage: gen_os9names.py path/to/os9.d > src/os9names.h"""
import sys
L = 2
lines = open(sys.argv[1], encoding='latin1').read().split('\n')
stack = [True]; loc = 0; out = {}
def ev(e):
    e = e.strip().split()[0] if e.strip() else ''
    e = e.replace('.', str(loc)).replace('$', '0x')
    try: return eval(e)
    except Exception: return None
for ln in lines:
    if ln.startswith('*'): continue
    f = ln.split()
    if not f: continue
    if ln[0] in ' \t': op = f[0].upper(); arg = f[1] if len(f) > 1 else ''; lab = None
    else: lab = f[0]; op = f[1].upper() if len(f) > 1 else ''; arg = f[2] if len(f) > 2 else ''
    if op.startswith('IF'):
        cond = {'IFGT': L-1 > 0, 'IFEQ': L-1 == 0, 'IFLT': L-1 < 0, 'IFNE': L-1 != 0}.get(op, True) if 'Level-1' in ln else True
        stack.append(stack[-1] and cond); continue
    if op == 'ELSE':
        par = stack[-2] if len(stack) > 1 else True
        stack[-1] = par and not stack[-1]; continue
    if op == 'ENDC': stack.pop(); continue
    if not stack[-1]: continue
    if op == 'ORG':
        v = ev(arg)
        if v is not None: loc = v
        continue
    if op == 'RMB':
        v = ev(arg)
        if lab and lab[:2] in ('F$', 'I$'): out[lab] = loc
        if v is not None: loc += v
print("/* generated by tools/gen_os9names.py from NitrOS-9 defs/os9.d - do not edit */")
print("static const struct { int code; const char *name; } os9_names[] = {")
for k, v in sorted(out.items(), key=lambda x: x[1]):
    if v < 0x70 or 0x80 <= v < 0x90: print('    { 0x%02x, "%s" },' % (v, k))
print("    { -1, 0 }\n};")
