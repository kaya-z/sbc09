"""mkcputest.py - writes scripts/cputest.s: a ROM for the real board that runs small tests of 6809 instructions and prints,
after each, the registers   NN A B X Y U CC   on the console UART.  The same ROM runs in the simulation (sim/Makefile ROM=cputest);
a line that differs between the two shows an instruction that the synthesized CPU does not execute like the simulated one."""
