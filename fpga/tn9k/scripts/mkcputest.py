 ("ldd #$1234", "cmpd #$1234"),
 ("ldx #$8000", "cmpx #$7FFF"),
 ("ldy #$8000", "cmpy #$8001"),
 ("ldu #$BEEF", "tfr u,d"),
 ("ldd #$CAFE", "tfr d,u"),
 ("ldx #$1357", "tfr x,y"),
 ("lda #$5A\n\tldb #$00", "tfr a,b"),
 ("ldx #$1111\n\tldy #$2222", "exg x,y"),
 ("lda #$12\n\tldb #$34", "exg a,b"),
 ("ldy #$1000\n\tldb #$05", "leax b,y"),
 ("ldy #$2000", "leay 5,y"),
 ("ldu #$2000", "leau -3,u"),
 ("ldu #$3000", "leax -2,u"),
 ("ldx #tptr", "ldx ,x"),
 ("ldb #$A5\n\tldx #tdat2", "stb ,x+"),
 ("ldx #tdat", "ldd ,x"),
 ("ldd #$1122\n\tldx #tdat2", "std ,x"),
 ("lda #$11\n\tldb #$22\n\tldx #$3344", "pshs a,b,x\n\tclra\n\tclrb\n\tldx #0\n\tpuls a,b,x"),
 ("lda #$55\n\tldx #$6677\n\tldu #$3000", "pshu a,x\n\tclra\n\tldx #0\n\tpulu a,x"),
