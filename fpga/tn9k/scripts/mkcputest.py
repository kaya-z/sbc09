 ("lda #$F0\n\tandcc #$FE", "adda #$10"),
 ("lda #$FF\n\torcc #$01", "adca #$00"),
 ("lda #$FF\n\tandcc #$FE", "adca #$00"),
 ("ldb #$7F\n\torcc #$01", "adcb #$00"),
 ("ldb #$80\n\tldx #tdat", "addb ,x+"),
 ("lda #$10\n\tandcc #$FE", "suba #$20"),
 ("lda #$10\n\torcc #$01", "sbca #$0F"),
 ("lda #$F0", "anda #$3C"),
 ("lda #$F0", "ora #$0F"),
 ("lda #$FF", "eora #$55"),
