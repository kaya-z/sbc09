"""genmap.py - lay out the memory map.

    genmap.py memmap.mk outdir

memmap.mk gives the sizes of the slots; the code slots follow each other from SYS_BASE, the data
slots from DATA_BASE, the transient program area starts behind the code of PM and the shell slot
is at its top.  Writes outdir/memmap.h (C) , outdir/memmap.inc (lwasm) and outdir/memmap.gen.mk."""
import os, re, sys

src, out = sys.argv[1], sys.argv[2]
over = dict(a.split('=') for a in sys.argv[3:])         # NAME=hex overrides (the C kernel needs a bigger data slot)
v = {}
high = []
for line in open(src, encoding='utf-8'):
    line = line.split('#')[0].strip()
    m = re.match(r'(\w+)\s*=\s*([0-9A-Fa-f]+)$', line)
    if m:
        v[m.group(1)] = int(m.group(2), 16)
    m = re.match(r'HIGH\s*=\s*(.*)$', line)
    if m:
        high = m.group(1).split()

for k, x in over.items():
    v[k] = int(x, 16)
res = []                                    # (name, value) in order
for k in ('VEC_BASE', 'SYS_BASE', 'DATA_BASE', 'TPA_END'):
    res.append((k, v[k]))
pc, pd = v['SYS_BASE'], v['DATA_BASE']
code = {}
data = {}
for m in ('K', 'TTY', 'DISK', 'FS', 'PM'):
    data[m] = pd
    pd += v[m + '_DSZ']
    if m not in high:
        code[m] = pc
        pc += v[m + '_CSZ']
for m in high:                          # these modules' code goes behind the data slots
    code[m] = pd
    pd += v[m + '_CSZ']
if pd > 0xFF00:
    sys.exit('genmap: data and high code do not fit below $FF00 (end %04X)' % pd)
for m in ('K', 'TTY', 'DISK', 'FS', 'PM'):
    res += [(m + '_CODE', code[m]), (m + '_CSZ', v[m + '_CSZ']), (m + '_DATA', data[m]), (m + '_DSZ', v[m + '_DSZ'])]
tpa = (pc + 0xFF) & ~0xFF
sh = v['TPA_END'] - v['SH_SIZE']
res += [('TPA_BASE', tpa), ('SH_BASE', sh), ('SH_END', v['TPA_END'])]
if tpa >= sh:
    sys.exit('genmap: the system code (end %04X) reaches the shell slot (%04X)' % (pc, sh))
os.makedirs(out, exist_ok=True)
with open(os.path.join(out, 'memmap.h'), 'w') as h:
    h.write('/* generated by tools/genmap.py from memmap.mk - do not edit */\n#ifndef MEMMAP_H\n#define MEMMAP_H\n')
    for k, x in res:
        h.write('#define %-10s 0x%04X\n' % (k, x))
    h.write('#endif\n')
with open(os.path.join(out, 'memmap.inc'), 'w') as a:
    a.write('* generated by tools/genmap.py from memmap.mk - do not edit\n')
    for k, x in res:
        a.write('%-10s equ $%04X\n' % (k, x))
with open(os.path.join(out, 'memmap.gen.mk'), 'w') as g:
    g.write('# generated by tools/genmap.py from memmap.mk - do not edit\n')
    for k, x in res:
        g.write('%s = %04X\n' % (k, x))
print('memory map: system code %04X-%04X, transient area %04X-%04X (%d bytes), shell slot %04X, data and high code %04X-%04X'
      % (v['SYS_BASE'], pc, tpa, v['TPA_END'], v['TPA_END'] - tpa, sh, v['DATA_BASE'], pd))
