def codes(chars, asc, codec):
    out = [ord(c) for c in asc]
    for c in chars:
        try:
            b = c.encode(codec)
        except UnicodeEncodeError:
            continue
        if codec == "utf-8":
            out.append(ord(c))
        elif len(b) == 2:
            out.append(b[0] << 8 | b[1])
    return out
def lit(s, codec):
    return "{" + ",".join(str(b - 256 if b > 127 else b) for b in s.encode(codec)) + ",0}"
